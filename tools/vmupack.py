"""
vmupack.py - Dreamcast VMU game packaging used by psbuild (target = vmu).

Builds the startup file that every VMU game needs (interrupt vectors, the
BIOS clock hook at $130, the exit hook at $1F0, the file header at $200
with the icon), assembles it together with the runtime and the game's own
sources using vmasm, and writes:

  <name>.vms   the game file (what emulators and VMU tools load)
  <name>.vmi   the small info file that goes with it (Dreamcast web browser,
               VMU managers and SD card tools want the pair)
  <name>.lst   listing with addresses and symbols, for debugging

File formats as documented by Marcus Comstedt's VMU pages.
"""
import os
import struct
import time

import psformat as pf
import vmasm

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VMU_DIR = os.path.join(KIT, 'vmu')
BLOCK = 512
MAX_GAME = 128 * 1024          # a VMU game can use at most 128 KB (one flash bank)

# mono icon colours (ARGB4444): light blue-grey background, dark ink
ICON_BG = 0xFCDE
ICON_FG = 0xF124


def crc16(data):
    n = 0
    for b in data:
        n ^= b << 8
        for _ in range(8):
            n = ((n << 1) ^ 0x1021) if n & 0x8000 else (n << 1)
            n &= 0xFFFF
    return n


def ascii_field(text, size, pad=b' '):
    raw = text.encode('ascii', 'replace')[:size]
    return raw + pad * (size - len(raw))


def argb4444(r, g, b, a):
    return ((a >> 4) << 12) | ((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4)


def load_icons(pdir, spec):
    """icon = a.txt, b.png ... -> (palette[16], [512-byte 4bpp frames])."""
    paths = [os.path.join(pdir, p.strip()) for p in spec.split(',') if p.strip()]
    if not paths:
        raise ValueError('project.ini: icon must name at least one 32x32 image')
    if len(paths) > 3:
        raise ValueError('a VMU file can have at most 3 icon frames')
    palette = [ICON_BG, ICON_FG]
    frames = []
    for p in paths:
        if p.lower().endswith('.png'):
            w, h, px = pf.read_png(p)
            if (w, h) != (32, 32):
                raise ValueError('%s: VMU icons are 32x32, this one is %dx%d' % (p, w, h))
            idx = []
            for row in px:
                for (r, g, b, a) in row:
                    c = argb4444(r, g, b, a)
                    if c not in palette:
                        palette.append(c)
                    idx.append(palette.index(c))
            if len(palette) > 16:
                raise ValueError('%s: VMU icons can use at most 16 colours (all frames together)' % p)
        else:
            rows = pf.load_mono(p)
            idx = [1 if (rows[y] >> x) & 1 else 0 for y in range(32) for x in range(32)]
        frame = bytearray(512)
        for i in range(0, 1024, 2):
            frame[i // 2] = (idx[i] << 4) | idx[i + 1]   # high nibble = left pixel
        frames.append(bytes(frame))
    palette += [0] * (16 - len(palette))
    return palette, frames


def header_bytes(cfg, palette, frames):
    """The 0x200.. file header: descriptions, creator, icon info, palette, icons."""
    h = bytearray()
    h += ascii_field(cfg['title'], 16)                       # $200 shown on the VMU
    h += ascii_field(cfg['description'] or cfg['title'], 32)  # $210 shown on the Dreamcast
    h += ascii_field(cfg['creator'], 16, b'\0')               # $230 creator application
    h += struct.pack('<HHHHI', len(frames), int(cfg['icon_delay'], 0) if len(frames) > 1 else 0,
                     0, 0, 0)                                 # $240 icons, speed, eyecatch, CRC, size
    h += bytes(20)                                            # $24C reserved
    h += struct.pack('<16H', *palette)                        # $260 palette
    for f in frames:                                          # $280 icon bitmaps
        h += f
    return bytes(h)


def bytes_lines(b):
    return ['        .byte ' + ','.join('$%02X' % x for x in b[i:i + 16]) for i in range(0, len(b), 16)]


def startup_source(cfg, header, sources):
    inc = lambda p: '        .include "%s"' % p.replace('\\', '/')
    L = ['; generated by psbuild from project.ini - do not edit',
         inc(os.path.join(VMU_DIR, 'include', 'vmu.i')),
         '',
         '        .org    $00',
         '        jmpf    vm__start           ; reset',
         '        .org    $03',
         '        reti                        ; INT0 (external)',
         '        .org    $0B',
         '        reti                        ; INT1 (external)',
         '        .org    $13',
         '        jmpf    vm__t0irq           ; INT2 / T0L overflow: frame timer',
         '        .org    $1B',
         '        jmpf    vm__timer           ; INT3 / base timer: keep the clock running',
         '        .org    $23',
         '        reti                        ; T0H overflow',
         '        .org    $2B',
         '        reti                        ; T1 overflow',
         '        .org    $33',
         '        reti                        ; SIO0',
         '        .org    $3B',
         '        reti                        ; SIO1',
         '        .org    $43',
         '        reti                        ; maple',
         '        .org    $4B',
         '        clr1    P3INT, 0            ; buttons',
         '        clr1    P3INT, 1',
         '        reti',
         '',
         '        .org    $130                ; BIOS clock update (base timer)',
         'vm__timer:',
         '        push    IE',
         '        clr1    IE, 7',
         '        not1    EXT, 0',
         '        jmpf    vm__timer           ; runs in the BIOS, which returns to $139',
         '        pop     IE',
         '        reti',
         '',
         '        .org    $1F0                ; leave the game',
         'vm__goodbye:',
         '        not1    EXT, 0',
         '        jmpf    vm__goodbye',
         '',
         '        .org    $200                ; file header and icon',
         ] + bytes_lines(header) + [
         '',
         'vm__start:',
         '        callf   vm_init',
         '        jmpf    main',
         '',
         inc(os.path.join(VMU_DIR, 'lib', 'vmu.s')),
         ''] + [inc(s) for s in sources]
    return '\n'.join(L) + '\n'


def make_vmi(cfg, vms_name, vms_size):
    res = os.path.splitext(os.path.basename(vms_name))[0][:8]
    res_b = res.encode('ascii', 'replace')
    resource = res_b + b'\0' * (8 - len(res_b))
    chk = bytes(resource[i] & b'SEGA'[i] for i in range(4))
    t = time.localtime()
    v = bytearray()
    v += chk
    v += ascii_field(cfg['description'] or cfg['title'], 32)
    v += ascii_field(cfg['creator'], 32)
    v += struct.pack('<HBBBBBB', t.tm_year, t.tm_mon, t.tm_mday, t.tm_hour, t.tm_min, t.tm_sec,
                     (t.tm_wday + 1) % 7)                     # 0 = Sunday
    v += struct.pack('<HH', 0, 1)                             # VMI version, file number
    v += resource
    fn = cfg['vmu_filename'].encode('ascii', 'replace')[:12]
    v += fn + b'\0' * (12 - len(fn))
    v += struct.pack('<HHI', 0x0002, 0, vms_size)             # mode: game, not copy protected
    assert len(v) == 108
    return bytes(v)


def build_vmu(cfg, pdir, bdir, sources, quiet=False):
    odir = os.path.join(bdir, 'obj')
    os.makedirs(odir, exist_ok=True)
    name = cfg['name']
    palette, frames = load_icons(pdir, cfg['icon'])
    header = header_bytes(cfg, palette, frames)
    main_s = os.path.join(odir, 'vmu_main.s')
    open(main_s, 'w').write(startup_source(cfg, header, sources))
    if not quiet:
        for s in sources:
            print('  asm  ' + os.path.relpath(s, pdir))
    inc = [os.path.join(VMU_DIR, 'include'), os.path.join(VMU_DIR, 'lib'),
           os.path.join(pdir, 'src'), pdir]
    lst = os.path.join(bdir, name + '.lst')
    binary, asm = vmasm.assemble_file(main_s, inc, lst)
    if 'main' not in asm.symbols:
        raise vmasm.AsmError('your game needs a label called "main" (where it starts)')
    data = bytearray(binary)
    if len(data) < 0x200 + len(header):
        raise vmasm.AsmError('game image is too short')
    data = data.ljust((len(data) + BLOCK - 1) // BLOCK * BLOCK, b'\0')
    if len(data) > MAX_GAME:
        raise vmasm.AsmError('game is %d bytes, a VMU game can be at most %d' % (len(data), MAX_GAME))
    struct.pack_into('<H', data, 0x246, 0)
    struct.pack_into('<H', data, 0x246, crc16(data))
    vms = os.path.join(bdir, name + '.vms')
    open(vms, 'wb').write(data)
    open(os.path.join(bdir, name + '.vmi'), 'wb').write(make_vmi(cfg, vms, len(data)))
    code_end = len(binary)
    print('   flash %6d bytes  (%d block%s of 512; free VMU space is up to 128 KB)' % (
        code_end, len(data) // BLOCK, 's' if len(data) > BLOCK else ''))
    print('   -> build/%s.vms  build/%s.vmi  (listing build/%s.lst)' % (name, name, name))
    return os.path.join(bdir, name)


def describe(path):
    """Text for 'ps info' on a .vms / .vmi file."""
    raw = open(path, 'rb').read()
    out = []
    if path.lower().endswith('.vmi') and len(raw) == 108:
        desc = raw[4:36].decode('ascii', 'replace').rstrip()
        fn = raw[88:100].rstrip(b'\0').decode('ascii', 'replace')
        res = raw[80:88].rstrip(b'\0').decode('ascii', 'replace')
        mode, = struct.unpack_from('<H', raw, 100)
        size, = struct.unpack_from('<I', raw, 104)
        out.append('file      : %s  (VMU info file)' % path)
        out.append('describes : %s.vms, %d bytes, "%s" on the VMU as %s' % (res, size, desc, fn))
        out.append('type      : %s%s' % ('game' if mode & 2 else 'data', ', copy protected' if mode & 1 else ''))
        return '\n'.join(out)
    if len(raw) < 0x280:
        return '%s: too small to be a VMU file' % path
    for base, kind in ((0x200, 'game'), (0, 'data')):
        icons, = struct.unpack_from('<H', raw, base + 0x40)
        if 1 <= icons <= 3:
            break
    else:
        base, kind, icons = 0x200, 'unknown', 0
    vdesc = raw[base:base + 16].decode('shift_jis', 'replace').rstrip()
    ddesc = raw[base + 16:base + 48].decode('shift_jis', 'replace').rstrip()
    creator = raw[base + 48:base + 64].rstrip(b'\0 ').decode('ascii', 'replace')
    crc_stored, = struct.unpack_from('<H', raw, base + 0x46)
    tmp = bytearray(raw)
    struct.pack_into('<H', tmp, base + 0x46, 0)
    out.append('file      : %s  (VMU %s file)' % (path, kind))
    out.append('title     : %s' % vdesc)
    out.append('dreamcast : %s' % ddesc)
    out.append('creator   : %s' % creator)
    out.append('size      : %d bytes = %d block(s)' % (len(raw), (len(raw) + BLOCK - 1) // BLOCK))
    out.append('crc       : $%04X (%s)' % (crc_stored, 'ok' if crc16(tmp) == crc_stored else 'differs'))
    out.append('icons     : %d frame(s)' % icons)
    if icons:
        pal = struct.unpack_from('<16H', raw, base + 0x60)
        ic = raw[base + 0x80:base + 0x80 + 512]
        for y in range(32):
            line = ''
            for x in range(32):
                b = ic[(y * 32 + x) // 2]
                n = (b >> 4) if x % 2 == 0 else (b & 15)
                c = pal[n]
                lum = ((c >> 8) & 15) * 3 + ((c >> 4) & 15) * 6 + (c & 15)
                line += '#' if (c >> 12) > 7 and lum < 80 else '.'
            out.append('   ' + line)
    return '\n'.join(out)
